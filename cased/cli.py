"""
cased2.0 / cli
==============

    python3 -m cased [path] [options]

Four stages, each independently inspectable in the output folder:

    analyze   repo      -> story.json
    score     duration  -> score.wav + beat map
    compose   story+map -> spec.json
    render    spec      -> cased.mp4
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

from .analyze import analyze, plural
from .insight import inspect
from .compose import compose
from .directors import DIRECTORS, pick
from . import themes as themes_mod
from . import score as score_mod

HERE = Path(__file__).resolve().parent

FORMATS = {
    "16:9":  (1920, 1080, "cased"),
    "9:16":  (1080, 1920, "cased-vertical"),
    "1:1":   (1080, 1080, "cased-square"),
    "4:5":   (1080, 1350, "cased-portrait"),
}

C = {
    "dim": "\033[2m", "b": "\033[1m", "r": "\033[0m",
    "pink": "\033[95m", "cyan": "\033[96m", "green": "\033[92m",
    "red": "\033[91m", "yellow": "\033[93m",
}
if not sys.stderr.isatty() or os.environ.get("NO_COLOR"):
    C = {k: "" for k in C}


def say(msg: str, icon: str = "·") -> None:
    sys.stderr.write(f"{C['dim']}{icon}{C['r']} {msg}\n")
    sys.stderr.flush()


def head(msg: str) -> None:
    sys.stderr.write(f"\n{C['pink']}{C['b']}{msg}{C['r']}\n")
    sys.stderr.flush()


def die(msg: str, code: int = 1):
    sys.stderr.write(f"{C['red']}error:{C['r']} {msg}\n")
    raise SystemExit(code)


def preflight(need_render: bool) -> None:
    """Fail early and tell the user exactly what to install."""
    missing = []
    if need_render:
        if not shutil.which("ffmpeg"):
            missing.append("ffmpeg   -- https://ffmpeg.org/download.html")
        if not shutil.which("node"):
            missing.append("node 18+ -- https://nodejs.org")
    if missing:
        die("missing prerequisites:\n   " + "\n   ".join(missing))


