def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="cased",
        description="Turn a repository into a cinematic launch film.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="directors:\n" + "\n".join(
            f"  {k:<11} {v['blurb']}" for k, v in DIRECTORS.items()),
    )
    p.add_argument("path", nargs="?", default=".", help="project directory (default: .)")
    p.add_argument("--director", "-d", choices=list(DIRECTORS),
                   help="pacing and shot grammar (default: chosen from the project)")
    p.add_argument("--theme", choices=themes_mod.names(), metavar="NAME",
                   help="palette and surface treatment; any of the "
                        f"{len(themes_mod.names())} themes works with any director "
                        "(see --list-themes)")
    p.add_argument("--duration", "-t", type=float, default=0.0,
                   help="runtime in seconds (default: 24, or 60 with --creative)")
    p.add_argument("--creative", "-c", action="store_true",
                   help="long-form mode: reads the architecture, the history and "
                        "the signature function, and cuts a detailed ~60s film")
    p.add_argument("--format", "-f", default="16:9",
                   help="16:9 | 9:16 | 1:1 | 4:5 | all (comma-separated ok)")
    p.add_argument("--quality", "-q", default="high", choices=["draft", "good", "high"])
    p.add_argument("--out", "-o", default="cased-output", help="output directory")
    p.add_argument("--seed", type=int, default=0, help="reproducibility seed")
    p.add_argument("--url", default="", help="override the project URL shown on the end card")
    p.add_argument("--tagline", default="", help="override the headline")
    p.add_argument("--no-audio", action="store_true", help="render silent")
    p.add_argument("--gif", action="store_true", help="also emit a looping GIF")
    p.add_argument("--plan-only", action="store_true",
                   help="write story.json + spec.json and stop (no render)")
    p.add_argument("--list-directors", action="store_true")
    p.add_argument("--list-themes", action="store_true",
                   help="every theme, grouped by family")
    p.add_argument("--list-graphics", action="store_true",
                   help="every graphic primitive the engine can draw")
    return p


def resolve_formats(spec: str) -> list:
    if spec.strip().lower() == "all":
        return list(FORMATS.items())
    out = []
    for token in spec.split(","):
        key = token.strip()
        if key not in FORMATS:
            die(f"unknown format {key!r}. choose from: {', '.join(FORMATS)} or 'all'")
        out.append((key, FORMATS[key]))
    return out


